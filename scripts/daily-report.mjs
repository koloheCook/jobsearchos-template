#!/usr/bin/env node
// daily-report: write reports/<today>.md, a plain summary of today's run that a
// person can open and read. Read-only over board-watch/out, landing/_ledger.md and
// opportunities/*/assessment.md; the only write is the report file itself.
// This is the default status surface; the Notion tracker mirror is optional.

import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";

const BANNER = /^## VERDICT: (PURSUE|EXPLORE|PASS)\b/;
const SCORES = /^Role-fits-you: (10|[0-9])\/10 \| You-fit-role: (10|[0-9])\/10 \| Gate: (RESOLVED-PASS|RESOLVED-FAIL|UNRESOLVED)$/;
const CONFIRMATION = /^Confirmed: (PURSUE|EXPLORE|PASS) by owner (\d{4}-\d{2}-\d{2})$/;

function localDate(date) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return `${year}-${month}-${day}`;
}

function parseArgs(argv) {
  const options = { root: process.cwd(), today: localDate(new Date()) };
  for (let index = 0; index < argv.length; index += 1) {
    if (argv[index] === "--root" && argv[index + 1]) options.root = path.resolve(argv[++index]);
    else if (argv[index] === "--today" && argv[index + 1]) options.today = argv[++index];
    else throw new Error(`unknown or incomplete argument: ${argv[index]} (usage: [--root <dir>] [--today YYYY-MM-DD])`);
  }
  if (!/^\d{4}-\d{2}-\d{2}$/.test(options.today)) throw new Error(`--today must be YYYY-MM-DD: ${options.today}`);
  return options;
}

async function readText(file) {
  try {
    return await readFile(file, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

async function listNames(directory) {
  try {
    return (await readdir(directory, { withFileTypes: true }));
  } catch (error) {
    if (error.code === "ENOENT") return [];
    throw error;
  }
}

// The newest board-watch run receipt written today, or null.
async function latestBoardRun(root, today) {
  const outDir = path.join(root, "board-watch", "out");
  const runs = (await listNames(outDir))
    .filter((entry) => entry.isFile() && /^run-.*\.json$/.test(entry.name))
    .map((entry) => entry.name)
    .sort();
  for (const name of runs.reverse()) {
    const run = JSON.parse(await readText(path.join(outDir, name)));
    if (typeof run.generatedAt === "string" && localDate(new Date(run.generatedAt)) === today) return run;
  }
  return null;
}

// Ledger rows whose processed date is today: | YYYY-MM-DD HH:MM | source | folder | verdict | note |
async function todaysLedgerRows(root, today) {
  const text = await readText(path.join(root, "landing", "_ledger.md"));
  if (!text) return [];
  return text
    .split(/\r?\n/)
    .filter((line) => line.startsWith(`| ${today}`))
    .map((line) => line.split("|").slice(1, -1).map((cell) => cell.trim()))
    .filter((cells) => cells.length >= 4)
    .map(([processed, source, folder, verdict, note = ""]) => ({ processed, source, folder, verdict, note }));
}

async function readAssessments(root) {
  const folders = (await listNames(path.join(root, "opportunities"))).filter((entry) => entry.isDirectory()).map((entry) => entry.name).sort();
  const assessments = [];
  for (const folder of folders) {
    const text = await readText(path.join(root, "opportunities", folder, "assessment.md"));
    if (!text) continue;
    const lines = text.split(/\r?\n/);
    const bannerIndex = lines.findIndex((line) => BANNER.test(line));
    if (bannerIndex === -1) continue;
    const scores = SCORES.exec(lines[bannerIndex + 1] ?? "");
    assessments.push({
      folder,
      verdict: BANNER.exec(lines[bannerIndex])[1],
      roleFits: scores?.[1] ?? "?",
      youFit: scores?.[2] ?? "?",
      gate: scores?.[3] ?? "?",
      confirmed: lines.some((line) => CONFIRMATION.test(line)),
    });
  }
  return assessments;
}

function render({ today, run, rows, assessments }) {
  const out = [`# Job search report ${today}`, "", `**Date:** ${today}`, "**Model, effort:** generated by scripts/daily-report.mjs (no model)", ""];

  out.push("## New postings found", "");
  if (!run) {
    out.push("The job-board check has not run today. Run `node board-watch/board-watch.mjs`.", "");
  } else {
    for (const result of run.results ?? []) {
      if (result.skipped === "seed_only") out.push(`- ${result.org}: first check, saved a baseline of current postings (nothing counts as new yet)`);
      else if (result.skipped) out.push(`- ${result.org}: could not check (${result.detail || result.skipped})`);
      else out.push(`- ${result.org}: ${result.added?.length ?? 0} new matching posting(s)`);
    }
    out.push("");
    for (const posting of run.emitted ?? []) out.push(`- ${posting.title} (${posting.org}, ${posting.location || "location not listed"}): ${posting.url}`);
    if ((run.emitted ?? []).length > 0) out.push("");
  }

  out.push("## Scored today", "");
  if (rows.length === 0) out.push("No jobs were scored today.", "");
  else {
    out.push("| Verdict | Role folder | Note |", "|---|---|---|");
    for (const row of rows) out.push(`| ${row.verdict} | ${row.folder} | ${row.note} |`);
    out.push("");
  }

  const waiting = assessments.filter((a) => a.verdict === "PURSUE" && !a.confirmed);
  out.push("## Waiting on you", "");
  if (waiting.length === 0) out.push("Nothing is waiting on you.", "");
  else {
    for (const a of waiting) out.push(`- PURSUE, not yet confirmed: ${a.folder} (role fits you ${a.roleFits}/10, you fit role ${a.youFit}/10). Open \`opportunities/${a.folder}/assessment.md\` and add a \`Confirmed:\` line if you agree.`);
    out.push("");
  }

  const counts = { PURSUE: 0, EXPLORE: 0, PASS: 0 };
  for (const a of assessments) counts[a.verdict] += 1;
  out.push("## All roles so far", "", `${assessments.length} scored: ${counts.PURSUE} PURSUE, ${counts.EXPLORE} EXPLORE, ${counts.PASS} PASS.`, "");

  out.push("## What to do next", "");
  if (waiting.length > 0) out.push("- Read each PURSUE above and decide. Apply yourself; the tool never applies.");
  if (rows.some((row) => row.verdict === "EXPLORE")) out.push("- For an EXPLORE, read the assessment's reasons and decide whether it is worth a closer look.");
  if (!run || (run.emitted ?? []).length === 0) out.push("- No new postings today. Found a job yourself? Clip it with the Chrome extension, or ask your assistant to capture a link, then run jd-intake.");
  out.push("- Call booked? Run meeting-brief (beta) with 2-3 goals for the call.", "");
  return `${out.join("\n")}`;
}

async function main() {
  const { root, today } = parseArgs(process.argv.slice(2));
  const report = render({
    today,
    run: await latestBoardRun(root, today),
    rows: await todaysLedgerRows(root, today),
    assessments: await readAssessments(root),
  });
  const file = path.join(root, "reports", `${today}.md`);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, report);
  console.log(`daily-report: wrote ${path.relative(root, file)}`);
}

main().catch((error) => {
  console.error(`daily-report: ${error.message}`);
  process.exitCode = 1;
});
